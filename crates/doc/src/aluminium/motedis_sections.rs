pub fn stock_section(model: &str) -> Option<solidcraft_geom::Region2> {
    use solidcraft_geom::{Loop2, Region2, Vec2};
    let (outer, voids): (&[[f64; 2]], &[&[[f64; 2]]]) = match model {
        "2020" => (P2020_OUTER, &[P2020_VOID1]),
        "3030" => (P3030_OUTER, &[P3030_VOID1, P3030_VOID2, P3030_VOID3, P3030_VOID4, P3030_VOID5]),
        _ => return None,
    };
    let loop_from = |points: &[[f64; 2]]| Loop2::polygon(&points.iter().map(|p| Vec2::new(p[0], p[1])).collect::<Vec<_>>());
    Some(Region2 { outer: loop_from(outer).ccw(), holes: voids.iter().map(|p| loop_from(p).ccw().reversed()).collect() })
}
